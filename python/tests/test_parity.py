# Python rounds some values for display; Rust keeps f32. Allowed absolute difference.
TOLERANCE = defaultdict(lambda: 1e-3, {
    "brake_pedal_pct": 0.051,
    "longitudinal_accel": 0.0051,
    "motor_angle": 0.051,
    "trip_fuel_l": 0.051,
    "trip_mpg": 0.051,
    "trip_l100km": 0.051,
})

# rust name -> reason. Lines for these names are not compared at all. Keep this empty
# unless a difference is deliberate; say why next to it.
KNOWN_DIFFS = {}


def _py_value(v):
    if v is None:
        return None
    if isinstance(v, bool):
        return v
    return v


def _rust_value(s):
    if s == "-":
        return None
    if s in ("true", "false"):
        return s == "true"
    try:
        return float(s)
    except ValueError:
        return s


def _same(name, rust, py):
    if rust is None or py is None:
        return rust is None and py is None
    if isinstance(rust, bool) or isinstance(py, bool):
        return bool(rust) == bool(py) and isinstance(py, bool) and isinstance(rust, bool)
    if isinstance(rust, float) and isinstance(py, (int, float)):
        return abs(rust - float(py)) <= TOLERANCE[name] * max(1.0, abs(rust) / 1000)
    return str(rust) == str(py)


class TestParity(unittest.TestCase):
    def test_every_rust_name_is_mapped(self):
        names = {l.split()[0] for l in VECTORS.read_text().splitlines() if l and not l.startswith("#")}
        self.assertEqual(sorted(names - set(KEYS) - set(KNOWN_DIFFS)), [], "add the Python key to KEYS")

    def test_python_matches_rust_vectors(self):
        bad = defaultdict(list)
        n = 0
        for line in VECTORS.read_text().splitlines():
            if not line or line.startswith("#"):
                continue
            name, cid, hexdata, val = line.split(" ", 3)
            if name in KNOWN_DIFFS:
                continue
            data = list(bytes.fromhex(hexdata))
            got = _py_value(parse_frame(int(cid, 16), data).get(KEYS[name]))
            want = _rust_value(val)
            n += 1
            if not _same(name, want, got):
                bad[name].append(f"{cid} {hexdata}: rust {val} python {got!r}")
        self.assertGreater(n, 1000)
        report = "\n".join(f"{k} ({len(v)}): " + "; ".join(v[:3]) for k, v in sorted(bad.items()))
        self.assertEqual(dict(bad), {}, "Rust and Python disagree:\n" + report)


