def unverified_bytes() -> list[tuple[int, int, str]]:
    out = []
    for cid, rows in BYTE_MAP.items():
        for i, (role, meaning) in enumerate(rows):
            if role == "unverified":
                out.append((cid, i, meaning))
    return out


def mux_unverified() -> list[tuple[int, int, int, str]]:
    out = []
    for cid, muxes in MUX_MAP.items():
        for mux, rows in muxes.items():
            for i, (role, meaning) in enumerate(rows):
                if role == "unverified":
                    out.append((cid, mux, i, meaning))
    return out
