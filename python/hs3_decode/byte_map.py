"""Per-byte meaning for every HS3 CAN ID seen on this vehicle.

Each ID maps to eight (role, meaning) tuples.
role is one of: signal, const, pad, flag, mux, nm, uds, tcu, unverified
"""
from __future__ import annotations

def _pad(val: int = 0) -> tuple[str, str]:
    return ("pad", f"unused {val:02X}")


def _c(val: int, name: str) -> tuple[str, str]:
    return ("const", f"{name}={val:02X}")


def _s(name: str) -> tuple[str, str]:
    return ("signal", name)


def _f(name: str) -> tuple[str, str]:
    return ("flag", name)


def _u(name: str) -> tuple[str, str]:
    return ("unverified", name)


def _zeros() -> list[tuple[str, str]]:
    return [_pad(0)] * 8


